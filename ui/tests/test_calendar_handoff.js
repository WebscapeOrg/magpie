const assert = require("node:assert/strict")
const {load} = require("./load")
const handoff = load("message/CalendarHandoff.js")
const invite = {uid:"private+recurrence@google", organizer:{email:"organizer@example.test",name:"unused"}, recurrenceIdMs:1793376000000, source:{recurrenceId:"RECURRENCE-ID;VALUE=DATE:20261030"}, summary:"🌤️".repeat(10000), method:"CANCEL", description:"x".repeat(100000), attendees:Array(1000).fill("unused")}
const result = handoff.invitation("personal",invite)
assert.ok(Buffer.byteLength(JSON.stringify(result)) < 5000)
for (const key of ["uid","recurrenceIdMs"]) assert.equal(result.invitation[key],invite[key])
assert.equal(result.invitation.organizer.email,invite.organizer.email)
assert.equal(result.invitation.source.recurrenceId,invite.source.recurrenceId)
assert.equal(result.invitation.method,"CANCEL")
assert.equal(result.invitation.description,undefined)
assert.equal(result.invitation.attendees,undefined)
assert.equal(invite.description.length,100000)
console.log("calendar handoff identity and size checks passed")
