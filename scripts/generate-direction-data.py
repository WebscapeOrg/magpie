#!/usr/bin/env python3
"""Regenerate both first-strong lookup tables from the pinned Unicode database."""
import argparse
import gzip
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
VERSION = "17.0.0"
SOURCE = ROOT / "data/unicode" / f"DerivedBidiClass-{VERSION}.txt.gz"
SHA256 = "4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4"
CODE_POINTS = 0x110000
NEUTRAL = 0
LEFT_TO_RIGHT = 1
RIGHT_TO_LEFT = 2
ENTRY = r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)"


def strong_class(name):
    if name in ("L", "Left_To_Right"):
        return LEFT_TO_RIGHT
    if name in ("R", "AL", "Right_To_Left", "Arabic_Letter"):
        return RIGHT_TO_LEFT
    return NEUTRAL


def classes():
    source = gzip.decompress(SOURCE.read_bytes())
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("Pinned Unicode source hash mismatch")
    text = source.decode("utf-8")
    result = bytearray([LEFT_TO_RIGHT]) * CODE_POINTS
    # Algorithm: Unicode's missing defaults apply before any explicit class assignment.
    for pattern in (r"^# @missing:\s*" + ENTRY, r"^" + ENTRY):
        for match in re.finditer(pattern, text, re.MULTILINE):
            start = int(match[1], 16)
            end = int(match[2] or match[1], 16)
            result[start:end + 1] = bytes([strong_class(match[3])]) * (end - start + 1)
    return result


def ranges(values):
    result = []
    start = 0
    for end in range(1, len(values) + 1):
        if end < len(values) and values[start] == values[end]:
            continue
        if values[start] != LEFT_TO_RIGHT:
            result.append((start, end - 1, "rtl" if values[start] == RIGHT_TO_LEFT else ""))
        start = end
    return result


def outputs(values):
    header = (f"// Generated by scripts/generate-direction-data.py; Unicode {VERSION}.\n"
              f"// DerivedBidiClass SHA-256: {SHA256}\n"
              "// Unicode data license: data/unicode/LICENSE.txt.\n")
    rows = ranges(values)
    javascript = ".pragma library\n\n" + header + "var RANGES = [\n"
    javascript += ",\n".join(f'  [0x{start:X}, 0x{end:X}, "{value}"]' for start, end, value in rows)
    javascript += "\n]\n"
    rust = header + "pub(super) const RANGES: &[(u32, u32, &str)] = &[\n"
    rust += "".join(f'    (0x{start:X}, 0x{end:X}, "{value}"),\n' for start, end, value in rows)
    rust += "];\n"
    return {ROOT / "ui/message/DirectionData.js": javascript,
            ROOT / "src/message/direction/data.rs": rust}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="verify checked-in tables without writing")
    mode.add_argument("--classes", action="store_true", help="emit one byte per code point:0=non-strong,1=L,2=R/AL")
    args = parser.parse_args()
    values = classes()
    if args.classes:
        sys.stdout.buffer.write(values)
        return
    for path, content in outputs(values).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit("Generated direction table differs: " + str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


if __name__ == "__main__":
    main()
