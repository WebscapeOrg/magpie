const assert = require('assert')
const {load, deepEqual} = require('./load.js')
const Display = load('settings/Display.js')
const initial = Display.normalize({})
assert.equal(initial.layout, 'Single pane')
for (const region of ['interface', 'list', 'message']) {
  assert.equal(initial[region + 'Family'], 'Chillax Light')
  assert.equal(initial[region + 'Size'], 17)
}
let saved = Display.changed(initial, 'layout', 'Split view')
saved = Display.changed(saved, 'interfaceFamily', '')
saved = Display.changed(saved, 'listSize', 24)
saved = Display.changed(saved, 'messageFamily', 'Liberation Serif')
deepEqual(Display.normalize(JSON.parse(JSON.stringify(saved))), saved)
assert.equal(saved.interfaceFamily, '')
assert.equal(saved.listSize, 24)
assert.equal(saved.interfaceSize, 17)
assert.equal(saved.messageSize, 17)
assert.equal(initial.layout, 'Single pane')
assert.equal(Display.changed(saved, 'layout', 'Single pane').listSize, 24)
for (const value of [NaN, Infinity, -1, 0, 7, 37, '<html>'])
  assert.equal(Display.changed(saved, 'messageSize', value).messageSize, 17)
assert.equal(Display.changed(saved, 'interfaceFamily', '<img src=x>').interfaceFamily, '')
assert.equal(Display.changed(saved, 'interfaceFamily', 'a\n').interfaceFamily, '')
assert.equal(Display.changed(saved, 'untrusted', 'value').untrusted, undefined)
console.log('Display preferences: defaults, independent fonts, round trip, bounds and hostile settings passed')

deepEqual(Display.fromWindow(JSON.stringify({display:saved, bodyZoom:1})), saved)
assert.equal(Display.fromWindow('broken').layout, 'Single pane')
