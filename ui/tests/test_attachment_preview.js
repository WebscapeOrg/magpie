const assert = require("assert")
const { load } = require("./load")
const preview = load("message/AttachmentPreview.js")
const png = "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aGNkAAAAASUVORK5CYII="
assert.equal(preview.rasterSource(png), png)
for (const value of ["https://example.invalid/image.png", "file:///etc/passwd", "data:image/svg+xml,<svg/>", "data:image/png;base64,PGltZyBzcmM9eD4=", png + "x".repeat(700000)])
  assert.equal(preview.rasterSource(value), "", "only bounded prepared PNG bytes reach Qt")
for (const mimeType of ["application/pdf", "image/png", "image/jpeg", "image/gif", "image/webp", "image/bmp"])
  assert.equal(preview.supported({attachmentId:"1",mimeType,size:4096}), true)
for (const file of [{attachmentId:"1",mimeType:"image/svg+xml"}, {attachmentId:"1",mimeType:"application/pdf",size:8388609}, {mimeType:"image/png"}])
  assert.equal(preview.supported(file), false)
assert.equal(preview.fileLabel({filename:"report.pdf",mimeType:"application/pdf"}), "PDF")
assert.equal(preview.fileLabel({filename:"budget.xlsx"}), "XLSX")
assert.equal(preview.fileLabel({filename:'<img src="https://example.invalid/">'}), "File")
