pub fn available() -> Vec<&'static str> {
    ALL.iter()
        .copied()
        .filter(|method| {
            !method.starts_with("agent.")
                || cfg!(all(feature = "agent", unix, not(target_os = "ios")))
        })
        .filter(|method| !method.starts_with("phone.") || cfg!(target_os = "linux"))
        .collect()
}
